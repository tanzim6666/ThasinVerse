function setupSoundSystem() {

    const toggle =
        document.getElementById("soundToggle");


    if (toggle) {

        toggle.addEventListener(
            "click",
            () => {

                soundEnabled =
                    !soundEnabled;


                updateSoundButton();


                if (soundEnabled) {

                    playUISound("success");

                }

            }
        );

    }


    document.addEventListener(
        "click",
        event => {

            const element =
                event.target.closest(".sound-btn");


            if (!element) return;

            if (
                element.id === "soundToggle"
            ) return;


            const soundType =
                element.dataset.sound ||
                "click";


            playUISound(soundType);

            createRipple(
                element,
                event
            );

        }
    );

}


function updateSoundButton() {

    const button =
        document.getElementById("soundToggle");


    if (!button) return;


    if (soundEnabled) {

        button.innerHTML = `

            <i class="fa-solid fa-volume-high"></i>

            <span>Sound</span>

        `;

        button.classList.remove(
            "sound-off"
        );

    } else {

        button.innerHTML = `

            <i class="fa-solid fa-volume-xmark"></i>

            <span>Muted</span>

        `;

        button.classList.add(
            "sound-off"
        );

    }

}


function playUISound(type = "click") {

    if (!soundEnabled) return;


    try {

        if (!audioContext) {

            audioContext =
                new (
                    window.AudioContext ||
                    window.webkitAudioContext
                )();

        }


        if (
            audioContext.state ===
            "suspended"
        ) {

            audioContext.resume();

        }


        const now =
            audioContext.currentTime;


        const oscillator =
            audioContext.createOscillator();

        const gain =
            audioContext.createGain();


        let frequency = 440;

        let duration = 0.12;


        if (type === "success") {

            frequency = 680;
            duration = 0.18;

        }

        else if (type === "open") {

            frequency = 560;
            duration = 0.14;

        }

        else if (type === "soft") {

            frequency = 380;
            duration = 0.08;

        }


        oscillator.type = "sine";

        oscillator.frequency.setValueAtTime(
            frequency,
            now
        );


        oscillator.frequency.exponentialRampToValueAtTime(
            frequency * 1.25,
            now + duration
        );


        gain.gain.setValueAtTime(
            0.0001,
            now
        );


        gain.gain.exponentialRampToValueAtTime(
            0.045,
            now + 0.015
        );


        gain.gain.exponentialRampToValueAtTime(
            0.0001,
            now + duration
        );


        oscillator.connect(gain);

        gain.connect(
            audioContext.destination
        );


        oscillator.start(now);

        oscillator.stop(
            now + duration + 0.02
        );

    }

    catch (error) {

        console.log(
            "Audio unavailable"
        );

    }

}


/* =========================================================
   RIPPLE EFFECT
========================================================= */

function createRipple(
    element,
    event
) {

    if (
        element.classList.contains(
            "class-card"
        ) ||
        element.classList.contains(
            "subject-card"
        ) ||
        element.classList.contains(
            "video-card"
        )
    ) {

        return;

    }


    const rect =
        element.getBoundingClientRect();


    const ripple =
        document.createElement("span");


    const size =
        Math.max(
            rect.width,
            rect.height
        );


    ripple.className =
        "click-ripple";


    ripple.style.width =
        `${size}px`;

    ripple.style.height =
        `${size}px`;


    ripple.style.left =
        `${event.clientX - rect.left - size / 2}px`;

    ripple.style.top =
        `${event.clientY - rect.top - size / 2}px`;


    element.appendChild(ripple);


    setTimeout(() => {

        ripple.remove();

    }, 650);

}


