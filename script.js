/* =========================================================
   YOUTUBE ID
========================================================= */

function getYoutubeId(url) {

    if (!url) return null;


    const patterns = [

        /youtu\.be\/([^?&]+)/,

        /youtube\.com\/watch\?v=([^?&]+)/,

        /youtube\.com\/shorts\/([^?&]+)/,

        /youtube\.com\/embed\/([^?&]+)/

    ];


    for (const pattern of patterns) {

        const match =
            url.match(pattern);

        if (match) {

            return match[1];

        }

    }


    return null;

}


/* =========================================================
   OPTIONAL VIDEO MODAL
========================================================= */

function openVideoModal(url) {

    const videoId =
        getYoutubeId(url);


    if (!videoId) {

        window.open(
            url,
            "_blank",
            "noopener,noreferrer"
        );

        return;

    }


    const modal =
        document.getElementById("videoModal");

    const frame =
        document.getElementById("youtubeFrame");


    frame.src =
        `https://www.youtube.com/embed/${videoId}?autoplay=1&rel=0`;


    modal.classList.add("active");

}


function closeVideoModal() {

    const modal =
        document.getElementById("videoModal");

    const frame =
        document.getElementById("youtubeFrame");


    frame.src = "";

    modal.classList.remove("active");

}


