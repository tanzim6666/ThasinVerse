function setupScrollProgress() {

    const progress =
        document.getElementById(
            "scrollProgress"
        );


    window.addEventListener(
        "scroll",
        () => {

            const scrollTop =
                window.scrollY;


            const height =
                document.documentElement
                    .scrollHeight -
                window.innerHeight;


            const percentage =
                height > 0
                ? (scrollTop / height) * 100
                : 0;


            progress.style.width =
                `${percentage}%`;

        },
        { passive: true }
    );

}


